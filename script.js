const THUMB_PARAMS = "?auto=format&fit=crop&w=400&q=50&fm=webp";
const FULL_RES_PARAMS = "?auto=format&fit=crop&w=1920&q=90";
const FALLBACK_IMG = `https://images.unsplash.com/photo-1507525428034-b723cf961d3e${THUMB_PARAMS}`;

// 1. Render Category Cards on index.html
function initHomeCategories() {
  const categoriesContainer = document.getElementById("categories-container");
  if (!categoriesContainer) return;

  Object.entries(categoryData).forEach(([key, data]) => {
    const label = key.charAt(0).toUpperCase() + key.slice(1);
    const figure = document.createElement("figure");
    figure.innerHTML = `
      <img src="${data.cover}${THUMB_PARAMS}" alt="${label} Wallpapers Category" loading="lazy" />
      <figcaption><h2>${label}</h2></figcaption>
    `;
    figure.addEventListener("click", () => {
      window.location.href = `category.html?type=${encodeURIComponent(key)}`;
    });
    categoriesContainer.appendChild(figure);
  });
}

// 2. Render Gallery Wallpapers on category.html
function initGallery() {
  const galleryContainer = document.getElementById("gallery-container");
  if (!galleryContainer) return;

  const params = new URLSearchParams(window.location.search);
  const selectedType = (params.get("type") || "cars").toLowerCase();
  const activeCategory = categoryData[selectedType] || categoryData.cars;

  const titleEl = document.getElementById("cat-title");
  if (titleEl) {
    titleEl.textContent = `${selectedType} wallpapers`;
  }
  document.title = `WALLIX | ${selectedType.toUpperCase()} Wallpapers`;

  activeCategory.images.forEach((baseUrl, index) => {
    const box = document.createElement("div");
    box.className = "box";
    box.innerHTML = `
      <img src="${baseUrl}${THUMB_PARAMS}"
           alt="${selectedType} Wallpaper ${index + 1}"
           loading="lazy"
           decoding="async"
           onerror="this.onerror=null; this.src='${FALLBACK_IMG}';" />
      <div class="download-overlay">
        <span class="download-btn"><i class="fa fa-download"></i> Download 4K</span>
      </div>
    `;

    box.addEventListener("click", () =>
      downloadWallpaper(baseUrl, `${selectedType}-wallpaper-${index + 1}`)
    );
    galleryContainer.appendChild(box);
  });
}

// 3. Download High-Resolution Image
async function downloadWallpaper(baseUrl, fileName) {
  const highResUrl = `${baseUrl}${FULL_RES_PARAMS}`;
  try {
    const response = await fetch(highResUrl);
    const blob = await response.blob();
    const blobUrl = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = blobUrl;
    link.download = `${fileName}.jpg`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(blobUrl);
  } catch (err) {
    window.open(highResUrl, "_blank");
  }
}

// 4. Handle Contact Form Submission & Mobile Menu Auto-Close
function initUI() {
  const contactForm = document.getElementById("contact-form");
  if (contactForm) {
    contactForm.addEventListener("submit", (e) => {
      e.preventDefault();
      alert("Thank you! Your message has been sent.");
      contactForm.reset();
    });
  }

  const toggler = document.getElementById("toggler");
  document.querySelectorAll(".navbar .link").forEach((link) => {
    link.addEventListener("click", () => {
      if (toggler) toggler.checked = false;
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  initHomeCategories();
  initGallery();
  initUI();
});